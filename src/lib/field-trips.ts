export function findTrip(slug: string) {
  return FIELD_TRIPS.find((t) => t.slug === slug);
}

const KEY = "geolens.trips.v1";
/** Furthest stop reached and completion, stored on this device only. */
export type TripProgress = Record<string, { seen: number; done?: boolean }>;
export function readTripProgress(): TripProgress {
  try {
    return JSON.parse(localStorage.getItem(KEY) || "{}") as TripProgress;
  } catch {
    return {};
  }
}
export function saveTripProgress(slug: string, seen: number, done = false) {
  try {
    const all = readTripProgress(),
      old = all[slug] ?? { seen: 0 };
    all[slug] = { seen: Math.max(old.seen, seen), done: old.done || done };
    localStorage.setItem(KEY, JSON.stringify(all));
  } catch {
    /* storage unavailable: progress is simply not kept */
  }
}
