export function atlasLabs(p: AtlasPlace): AtlasLabLink[] {
  const label = (slug: string) => LAB_LABEL_FOR[p.id]?.[slug] ?? LAB_BY_SLUG[slug]?.title ?? slug;
  if (RECS[p.id]) return RECS[p.id].map((slug) => ({ slug, label: label(slug) }));
  if (p.labs?.length)
    return p.labs
      .slice(0, 3)
      .map((l) => ({ ...l, label: LAB_LABEL_FOR[p.id]?.[l.slug] ?? l.label }));
  const blob = `${p.name} ${p.hook} ${(p.geo ?? []).join(" ")}`.toLowerCase();
  const out: AtlasLabLink[] = [];
  const add = (slug: string, label: string) => {
    if (!out.some((x) => x.slug === slug)) out.push({ slug, label });
  };
  if (/\bvolcan|island arc|ring of fire/.test(blob)) add("volcanoes", "Volcanoes");
  if (/earthquake|\bfaults?\b|subduct/.test(blob)) add("earthquakes", "Earthquakes");
  if (/\bplates?\b(?! *(?:hinge|edge))|mid-ocean ridge|trench|transform|\brift\b/.test(blob))
    add("plate-boundaries", "Plate boundaries");
  if (/hotspot/.test(blob)) add("hotspots", "Hotspots");
  if (/\bglacia|\bice\b|fjord|cirque|u-trough|drumlin|\btill\b|moraine/.test(blob))
    add("glaciers", "Glacial landforms");
  if (/(?<!no )\bcoast|\bspit\b|\bcliffs?\b|longshore|barrier/.test(blob)) add("coasts", "Coasts");
  if (/hurricane|cyclone|typhoon|storm surge/.test(blob))
    add("tropical-cyclone", "Tropical cyclone");
  if (/karst|limestone|\bcaves?\b|sinkhole/.test(blob)) add("karst", "Karst");
  if (/\briver|delta|\bnile\b|amazon|meander|flood/.test(blob)) add("rivers", "Rivers");
  if (/monsoon|itcz|climate|desert|rain-shadow|rain shadow/.test(blob))
    add("climate-types", "Climate types");
  if (/\bsoils?\b|loess|mollisol|chernozem/.test(blob)) add("soil-profile", "Soil profile");
  if (/\bfold|anticline|syncline/.test(blob)) add("folds-faults", "Folds and faults");
  return out.slice(0, 3);
}

export function nearestAtlasPlace(lat: number, lon: number, maxDeg = 12): AtlasPlace | null {
  let best: AtlasPlace | null = null;
  let d0 = maxDeg * maxDeg;
  const cos = Math.cos((lat * Math.PI) / 180) ** 2;
  for (const p of ATLAS) {
    const d = (p.lat - lat) ** 2 + (((p.lon - lon + 540) % 360) - 180) ** 2 * cos;
    if (d < d0) {
      d0 = d;
      best = p;
    }
  }
  return best;
}

