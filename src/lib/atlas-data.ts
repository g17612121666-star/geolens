const fold = (s: string) =>
  s
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[ʻ’']/g, "")
    .toLowerCase()
    .trim();

export type AtlasHit = { place: AtlasPlace; match?: string; score: number };

/**
 * Ranked place search: exact name, then a name starting with the query, then exact alias or
 * landmark, then any word in a name, capital, alias or landmark starting with the query.
 */
export function atlasSearch(query: string): AtlasHit[] {
  const q = fold(query);
  if (!q) return [];
  const hits: AtlasHit[] = [];
  for (const place of ATLAS) {
    const name = fold(place.name);
    const extras = [
      ...(place.capital !== "—" ? [place.capital] : []),
      ...(place.alias ?? []),
      ...(LANDMARKS[place.id] ?? []),
    ];
    let best: AtlasHit | null = null;
    const consider = (score: number, match?: string) => {
      if (!best || score > best.score) best = { place, match, score };
    };
    if (name === q) consider(100);
    else if (name.startsWith(q)) consider(80);
    else if (name.split(/[\s–-]+/).some((w) => w.startsWith(q))) consider(60);
    for (const extra of extras) {
      const e = fold(extra);
      if (e === q) consider(90, extra);
      else if (e.startsWith(q)) consider(70, extra);
      else if (q.length >= 3 && e.split(/[\s–-]+/).some((w) => w.startsWith(q)))
        consider(50, extra);
    }
    if (best) hits.push(best);
  }
  const KIND_ORDER = ["us-state", "country", "city", "uk-place", "uk-nation", "uk-county"];
  return hits.sort(
    (a, b) =>
      b.score - a.score ||
      KIND_ORDER.indexOf(a.place.kind) - KIND_ORDER.indexOf(b.place.kind) ||
      a.place.name.localeCompare(b.place.name),
  );
}

